/** (x, z) 在不在矩形 [x0, z0, x1, z1] 裡；左下兩邊算在裡面、右上兩邊不算，相鄰的矩形才不會重疊 */
export const inside = ([x0, z0, x1, z1], x, z) => x >= x0 && x < x1 && z >= z0 && z < z1;

/** 店面配置 layout 在 (x, z) 的地面高度 */
export function groundAt(layout, x, z) {
  let y = 0;
  for (const { rect, y: h } of layout.floors) if (inside(rect, x, z)) y = Math.max(y, h);
  return y;
}

/**
 * 可走範圍 walkable（矩形的清單）以外的地方，切成一塊塊的方框，少女行為把它們當成牆一樣推開
 * 可走範圍往外多算 margin 公尺，所以牆是一整圈 margin 公尺厚的；凹角、交接處也都是實心的，不會被擠過去
 * 作法：用所有矩形的邊界把平面切成格子，沒被任何矩形蓋到的格子就是擋住的，再把相鄰、同寬的格子併起來
 */
export function outsideOf(walkable, margin = 1) {
  const xs = [...new Set(walkable.flatMap(r => [r[0], r[2]]))].sort((a, b) => a - b);
  const zs = [...new Set(walkable.flatMap(r => [r[1], r[3]]))].sort((a, b) => a - b);
  xs.unshift(xs[0] - margin); xs.push(xs.at(-1) + margin);
  zs.unshift(zs[0] - margin); zs.push(zs.at(-1) + margin);
  const open = (i, j) => walkable.some(([x0, z0, x1, z1]) => xs[i] >= x0 && xs[i + 1] <= x1 && zs[j] >= z0 && zs[j + 1] <= z1);
  // 每一列（同一段 z）裡連續擋住的格子併成一條
  const rows = [];
  for (let j = 0; j < zs.length - 1; j++) {
    for (let i = 0; i < xs.length - 1; i++) {
      if (open(i, j)) continue;
      const last = rows.at(-1);
      if (last && last.j === j && last.i1 === i) last.i1 = i + 1;
      else rows.push({ i0: i, i1: i + 1, j0: j, j1: j + 1, j });
    }
  }
  // 上下相鄰、左右範圍一樣的條併成一塊
  const boxes = [];
  for (const row of rows) {
    const above = boxes.find(b => b.i0 === row.i0 && b.i1 === row.i1 && b.j1 === row.j0);
    if (above) above.j1 = row.j1; else boxes.push({ ...row });
  }
  return boxes.map(b => [xs[b.i0], zs[b.j0], xs[b.i1], zs[b.j1]]);
}
